#!/usr/bin/env node
// Generates docs/RULES.md (rule index and ATT&CK coverage) and docs/playbooks/<ruleId>.md
// (analyst triage playbook per rule) from the rule YAML files.
'use strict';

const fs = require('fs');
const path = require('path');
const { ROOT, loadRules, ruleTables } = require('./lib');

const DOCS = path.join(ROOT, 'docs');
const PLAYBOOKS = path.join(DOCS, 'playbooks');
const SEVERITY_ORDER = { High: 0, Medium: 1, Low: 2, Informational: 3 };

function techniqueLink(id) {
  return `[${id}](https://attack.mitre.org/techniques/${id.replace('.', '/')}/)`;
}

function splitWords(tactic) {
  return tactic.replace(/([a-z])([A-Z])/g, '$1 $2');
}

function playbook(rule) {
  const t = rule.triage;
  const lines = [
    `# ${rule.ruleId}: ${rule.name}`,
    '',
    `**Severity:** ${rule.severity} · **Tactics:** ${rule.tactics.map(splitWords).join(', ')} · ` +
      `**Techniques:** ${rule.relevantTechniques.map(techniqueLink).join(', ')} · ` +
      `**Data:** ${ruleTables(rule).join(', ')}`,
    '',
    rule.description.trim(),
    '',
    '## Triage steps',
    '',
    ...t.steps.map((s, i) => `${i + 1}. ${s}`),
    '',
    '## Common false positives',
    '',
    ...t.falsePositives.map((s) => `- ${s}`),
    '',
    '## Escalate when',
    '',
    t.escalateWhen.trim(),
    '',
    '## Query',
    '',
    '```kql',
    rule.query.trim(),
    '```',
    '',
    `Runs every ${rule.queryFrequency} over the last ${rule.queryPeriod}. Source: [\`rules/${rule.file}\`](../../rules/${rule.file})`,
    '',
  ];
  return lines.join('\n');
}

function index(rules) {
  const sorted = [...rules].sort((a, b) =>
    SEVERITY_ORDER[a.severity] - SEVERITY_ORDER[b.severity] || a.ruleId.localeCompare(b.ruleId));
  const lines = [
    '# Rules',
    '',
    '_Generated by `npm run docs` from the files in `rules/`. Do not edit by hand._',
    '',
    '| ID | Rule | Severity | Data | ATT&CK |',
    '|---|---|---|---|---|',
    ...sorted.map((r) =>
      `| [${r.ruleId}](playbooks/${r.ruleId}.md) | ${r.name} | ${r.severity} | ${ruleTables(r).join(', ')} | ` +
      `${r.relevantTechniques.map(techniqueLink).join(', ')} |`),
    '',
    '## ATT&CK coverage by tactic',
    '',
    '| Tactic | Rules |',
    '|---|---|',
  ];
  const byTactic = new Map();
  for (const r of rules) for (const t of r.tactics) {
    if (!byTactic.has(t)) byTactic.set(t, []);
    byTactic.get(t).push(r.ruleId);
  }
  const tacticOrder = ['InitialAccess', 'Execution', 'Persistence', 'PrivilegeEscalation', 'DefenseEvasion',
    'CredentialAccess', 'Discovery', 'LateralMovement', 'Collection', 'Exfiltration', 'Impact'];
  for (const t of tacticOrder) {
    if (byTactic.has(t)) lines.push(`| ${splitWords(t)} | ${byTactic.get(t).sort().join(', ')} |`);
  }
  lines.push('');
  return lines.join('\n');
}

function main() {
  const rules = loadRules();
  fs.mkdirSync(PLAYBOOKS, { recursive: true });
  for (const f of fs.readdirSync(PLAYBOOKS)) if (f.endsWith('.md')) fs.unlinkSync(path.join(PLAYBOOKS, f));
  for (const rule of rules) fs.writeFileSync(path.join(PLAYBOOKS, `${rule.ruleId}.md`), playbook(rule));
  fs.writeFileSync(path.join(DOCS, 'RULES.md'), index(rules));
  console.log(`wrote docs/RULES.md and ${rules.length} playbooks`);
}

main();
